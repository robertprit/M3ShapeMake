import org.json.JSONArray
import org.json.JSONObject

object VectorDrawableExport : ShapeMakerExporter<ExportResult> {
    override val target = "android-vector-drawable"
    override fun export(document: ShapeMakerDocument): ExportResult {
        val geometry = document.assets.geometry
        val objects = geometry.allObjects()
        val warnings = buildList {
            if (objects.size > 1) add(ExportWarning("FLATTENED_LAYERS", "VectorDrawable exports visible objects as flat paths"))
            if (document.animations.isNotEmpty()) add(ExportWarning("ANIMATION_METADATA", "VectorDrawable does not contain timeline animation"))
        }
        val paths = objects.joinToString("\n") { obj ->
            val path = GeometryToPath.toPath(obj.geometry, obj.semantics.parameters)
            "    <path android:fillColor=\"#${obj.fill.color.toArgb().toUInt().toString(16).padStart(8, '0').uppercase()}\" android:pathData=\"${pathData(path.segments)}\" />"
        }
        val vb = geometry.canvas.effectiveViewBox
        val xml = """<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${vb.width}dp" android:height="${vb.height}dp"
    android:viewportWidth="${vb.width}" android:viewportHeight="${vb.height}">
$paths
</vector>"""
        return ExportResult(xml, warnings)
    }
}

object ImageVectorExport : ShapeMakerExporter<ExportResult> {
    override val target = "compose-image-vector"
    override fun export(document: ShapeMakerDocument): ExportResult {
        val className = document.metadata.name.filter(Char::isLetterOrDigit).ifBlank { "Asset" }
        val objects = document.assets.geometry.allObjects()
        val paths = objects.joinToString("\n") { obj ->
            val geometry = GeometryToPath.toPath(obj.geometry, obj.semantics.parameters)
            val color = obj.fill.color.toArgb().toUInt().toString(16).padStart(8, '0').uppercase()
            """        addPath(
            pathData = PathParser().parsePathString("${pathData(geometry.segments)}").toNodes(),
            fill = SolidColor(Color(0x${color}))
        )"""
        }
        val source = """// Generated by ShapeMaker
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

val ${className}Vector: androidx.compose.ui.graphics.vector.ImageVector
    get() = androidx.compose.ui.graphics.vector.ImageVector.Builder(
        name = "$className", defaultWidth = 24.dp, defaultHeight = 24.dp,
        viewportWidth = ${document.canvas.width}f, viewportHeight = ${document.canvas.height}f
    ).apply {
$paths
    }.build()
"""
        return ExportResult(source, buildList {
            if (document.animations.isNotEmpty()) add(ExportWarning("ANIMATION_METADATA", "ImageVector is static; animation stays in visual metadata"))
        })
    }
}

object VisualMetadataExport : ShapeMakerExporter<ExportResult> {
    override val target = "visual-metadata"
    override fun export(document: ShapeMakerDocument): ExportResult = ExportResult(
        JSONObject().apply {
            put("format", "shapemaker-visual-metadata")
            put("version", 1)
            put("assetId", document.metadata.documentId)
            put("name", document.metadata.name)
            put("states", JSONArray(document.states.map { it.id }))
            put("transitions", JSONArray(document.transitions.map { transition ->
                JSONObject().apply {
                    put("id", transition.id)
                    put("from", transition.fromState)
                    put("to", transition.toState)
                    put("durationMs", transition.durationMs)
                }
            }))
            put("animations", JSONArray(document.animations.map { animation ->
                JSONObject().apply {
                    put("id", animation.id)
                    put("name", animation.name)
                    put("tracks", JSONArray(animation.tracks.map { track ->
                        JSONObject().apply {
                            put("id", track.id)
                            put("channel", track.channel.name)
                            put("targetObjectId", track.targetObjectId)
                            put("keyframeCount", track.keyframes.size)
                        }
                    }))
                    put("events", JSONArray(animation.events.map { event ->
                        JSONObject().apply {
                            put("id", event.id)
                            put("name", event.name)
                            put("timeMs", event.timeMs)
                        }
                    }))
                }
            }))
            put("sequences", JSONArray(document.sequences.map { it.id }))
            put("interactions", JSONObject(document.interactionMetadata))
        }.toString(2)
    )
}

private fun pathData(segments: List<PathSegment>): String = segments.joinToString(" ") { segment ->
    when (segment) {
        is PathSegment.MoveTo -> "M${segment.x},${segment.y}"
        is PathSegment.LineTo -> "L${segment.x},${segment.y}"
        is PathSegment.QuadraticBezierTo -> "Q${segment.cx},${segment.cy} ${segment.x},${segment.y}"
        is PathSegment.CubicBezierTo -> "C${segment.cx1},${segment.cy1} ${segment.cx2},${segment.cy2} ${segment.x},${segment.y}"
        PathSegment.Close -> "Z"
    }
}
